"""Пороги склейки и событий. Все числа — здесь, чтобы подстраивать их по живым данным.

Определения порогов взяты из SKILL.md («Склейка объектов», «Валюта и цены»). Значения,
которых в скилле нет (радиусы, льготное окно продавца), обоснованы в комментариях.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import timedelta
from decimal import Decimal


@dataclass(frozen=True)
class MatchingConfig:
    # --- Уровень 1, отпечаток ---
    # Площадь: площадки округляют по-разному (54 / 54.2 / 54.3), продавцы путают общую и жилую.
    area_tolerance_m2: float = 1.0

    # --- Уровень 2, фото ---
    # Расстояние Хэмминга между 64-битными phash: ≤ 8 переживает пережатие, ресайз и водяной знак.
    phash_max_distance: int = 8
    # Два и более совпавших фото — один объект (SKILL.md). Одно совпадение бывает и у соседей:
    # общий снимок фасада, двора или типовой планировки.
    phash_min_matches: int = 2
    # Если у обоих объявлений хотя бы столько информативных фото, а совпало меньше
    # phash_min_matches, фото противоречат склейке: это другие квартиры (или переснятая, но
    # пропущенная склейка лучше ложной).
    photo_min_for_contradiction: int = 3

    # --- Координаты ---
    # Радиус «тот же дом». Длинная панельная девятиэтажка в Минске — 100–150 м, точка геокодера
    # стоит то в центре здания, то у подъезда, а Kufar и Realt геокодируют по-разному
    # (расхождение десятки метров). 100 м покрывает один дом почти всегда, но в плотном
    # микрорайоне захватывает 1–3 соседних. Поэтому совпадение только по координатам
    # даёт не больше `low`, а нескольких кандидатов считаем неоднозначностью (новый объект).
    geo_radius_m: float = 100.0
    # Дальше этого объявления точно про разные дома, даже если адрес совпал
    # (одноимённые улицы в Минском районе, ошибка геокодера на одной из площадок).
    geo_contradiction_m: float = 500.0

    # --- Продавец ---
    # Агентство при перевыкладывании часто сначала публикует новое объявление, а старое
    # снимает позже. Пока оба висят меньше этого срока, новое объявление ждёт (не склеиваем
    # и не создаём объект). Дольше — значит, у продавца две похожие квартиры (новостройка).
    same_seller_overlap_grace: timedelta = timedelta(days=1)

    # --- События ---
    relisted_window: timedelta = timedelta(days=30)
    removed_after: timedelta = timedelta(days=3)
    # Минимальное изменение цены в исходной валюте, % (отсекает шум округления).
    price_change_min_pct: Decimal = Decimal("0.5")
    # Какие объекты пересчитывать после прохода: недавно виденные. Запас поверх removed_after
    # на случай, если обработка несколько дней не запускалась. full=True — пересчитать всё.
    events_lookback: timedelta = timedelta(days=10)


DEFAULT_CONFIG = MatchingConfig()
