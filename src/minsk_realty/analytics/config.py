"""Пороги аналитики. Все числа — здесь, чтобы калибровать их по живым данным.

Что взято из документов, а что — допущение Leo, отмечено в комментариях. Допущения
пересматриваем на 6-й неделе, когда будет видно, после каких сигналов объекты уходят с рынка.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import timedelta


@dataclass(frozen=True)
class AnalyticsConfig:
    # --- Малые выборки ---
    # Меньше 10 объектов в группе — медиану не показываем (правило Leo, см. агента).
    min_sample: int = 10

    # --- Медианы $/м² ---
    # Грубый фильтр мусора до IQR: цена за м² в Минске вне этих границ — почти наверняка
    # опечатка (цена за м² вместо цены квартиры, BYN в поле USD, площадь 5 м²).
    ppm_bounds_usd: tuple[float, float] = (300.0, 10_000.0)
    area_bounds_m2: tuple[float, float] = (10.0, 500.0)
    # Выбросы — по Тьюки: вне [Q1 − k·IQR, Q3 + k·IQR]. Применяется, если в группе ≥ 4 точек.
    iqr_k: float = 1.5

    # --- Срок экспозиции ---
    # Объявление, впервые замеченное в первые сутки наблюдения площадки, висело и раньше:
    # его срок — «как минимум». Сутки — запас на то, что первый полный проход занимает время.
    truncation_margin: timedelta = timedelta(days=1)
    # Дата публикации площадки старше этого срока до первого замера — скорее мусор.
    posted_at_max_age: timedelta = timedelta(days=3 * 365)
    # «Видим впервые»: объявление моложе этого срока, без других объявлений и событий цены.
    first_time_window: timedelta = timedelta(days=2)
    # На сайте объявление «моложе» реального срока минимум на столько — стоит сказать.
    site_counter_gap_days: int = 7

    # --- Индекс торга (допущения, не откалиброваны) ---
    long_ratio_high: float = 2.0  # срок ≥ 2× медианы по району → +2
    long_ratio_mid: float = 1.25  # срок ≥ 1.25× медианы → +1
    # Если медианы срока нет (мало данных), абсолютные пороги.
    long_days_high: int = 90
    long_days_mid: int = 45
    fresh_days: int = 14  # меньше — «свежее», торг слабее (−1)
    median_gap_pct: float = 10.0  # ±10% к медиане $/м² — заметное отклонение
    cheaper_min_pct: float = 0.5  # дешевле на другой площадке хотя бы на 0.5% (как порог цены)
    level_high: int = 4
    level_medium: int = 2
    # Ориентир первого предложения, % ниже самой низкой цены этой квартиры (min, max).
    # Эвристика, сверена только с примером из docs/02 (1.2): $92 500, на Onliner $91 000 →
    # «начните с $88–89k».
    offer_pct_high: tuple[float, float] = (3.0, 5.0)
    offer_pct_medium: tuple[float, float] = (1.5, 3.0)

    # --- Сводки ---
    # Снижение больше этого в «топ недели» не попадает: скорее исправили опечатку в цене.
    max_public_drop_pct: float = 25.0
    top_drops: int = 3

    # --- Гипотеза (docs/01-idea.md, раздел 9) ---
    hypothesis_weeks: int = 6
    # Пограничный итог 6 недель не решаем, а продлеваем наблюдение до стольких недель.
    extended_weeks: int = 12
    # «≥10% объектов перевыкладывались или есть на нескольких площадках» — из идеи.
    relist_or_cross_min: float = 0.10
    # «у заметной доли есть снижения» — порога в идее нет, берём 10% (подтвердить).
    drops_min: float = 0.10
    # «отчёт по случайной квартире показывает что-то, чего не видно на сайте»:
    # у большинства (≥ 50%) объектов есть хотя бы одна такая находка (допущение).
    insight_min: float = 0.50
    # «перевыкладываний и расхождений почти нет» — меньше 5% (допущение).
    stop_max: float = 0.05
    # Объект «зрелый», если мы видим его хотя бы столько: у новых объектов ещё не было
    # времени перевыложиться или подешеветь.
    mature_after: timedelta = timedelta(days=14)
    min_objects: int = 200
    sample_size: int = 5

    # --- Точность координат ---
    # Площадки, у которых координата — центр района или улицы, а не дом: доля объявлений в
    # точках, общих для разных домов, больше 0.10. Сверка живой базы 24.10.2026
    # (scripts/check_coords.py; адрес — у склеенного объекта, иначе из снимка; объявления без
    # адреса не сравниваются): domovita 0.260 (3048 объявлений с адресом), realt 0.101 (6381),
    # kufar 0.089 (8433), onliner 0.026 (1023). Realt чуть выше порога, kufar чуть ниже.
    # Расстояние до метро и «соседей рядом» по площадкам из списка не считаем.
    approx_coord_sources: frozenset[str] = frozenset({"domovita", "realt"})


DEFAULT_ANALYTICS = AnalyticsConfig()
